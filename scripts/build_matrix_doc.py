#!/usr/bin/env python3
"""
build_matrix_doc.py — write references/tone-matrix.md from assets/style_matrix.json.

The JSON is the single source for the matrix and for the settings page
(scripts/settings.py), so the document and the page cannot disagree. Run after
any change to the JSON. Python 3.8+, standard library only.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
M = json.loads((ROOT / "assets" / "style_matrix.json").read_text(encoding="utf-8"))
DIM = {d["key"]: d for d in M["dims"]}
SYM = M["levels"]
TONE = ["distance", "certainty", "warmth"]


def row(cells):
    return "| " + " | ".join(cells) + " |"


def table(head, rows):
    return "\n".join([row(head), row(["---"] * len(head))] + [row(r) for r in rows])


def reg_cell(reg, key):
    lim = M["register_limits"].get(reg, {}).get(key, {})
    return " / ".join(SYM[lim.get(v["v"], "ok")] for v in DIM[key]["values"])


def recipe_cell(r, key):
    d = r["def"][key]
    others = [v for v in r["allow"][key] if v != d]
    return f"**{d}**" + (f" ({'، '.join(others)})" if others else "")


out = []
out.append("""# ماتریس سیاق، لحن و سبک

<!-- Generated by scripts/build_matrix_doc.py from assets/style_matrix.json. Edit the JSON, then rerun. -->

This file holds every dimension the skill uses to decide how a text sounds, in
the order in which they are decided, with one criterion per dimension. It is
written in Persian because its tables are meant for the user as much as for
the model. The same data drives the advanced-settings page
(`scripts/settings.py`), so the two cannot disagree.

همه‌ی مثال‌ها ساختگی‌اند و روی یک موضوع نوشته شده‌اند تا فقط فرق هر مقدار دیده شود. موضوع مثال‌ها این است که """ + M["example_topic"])

out.append("""## ۱. ترتیب تصمیم‌ها

| گام | چه چیزی تعیین می‌شود | کی | ثابت یا متغیر |
| --- | --- | --- | --- |
| ۱ | سیاق | پیش از روایت | در کل متن ثابت |
| ۲ | جایگاه (من، ما، بیرونی) | پیش از روایت | ثابت؛ فقط در مرز بخش و با دلیل عوض می‌شود |
| ۳ | نسخه، و غایت و شاهد و ساخت آن | پیش از روایت | در کل متن یک غایت |
| ۴ | روایت سطح ۱ و تیترها، با فاصله و دما و آهنگ هر تیتر | سطح ۱ | از بخشی به بخش دیگر، هر بار یک پله |
| ۵ | روایت هر بخش و قاطعیت هر ادعا | سطح ۲ | ادعا به ادعا |
| ۶ | دمای جمله‌ها، تصویر، مثل و آهنگ واقعی | نوشتن متن | جمله به جمله، درون مرز بخش |

روایت با زبان ساده و خنثی نوشته می‌شود تا فقط منطقش داوری شود. لحن نهایی در گام ۶ می‌آید.""")

out.append("## ۲. بُعدها، هر کدام با یک مقسم\n\n" + table(
    ["بُعد", "مقسم", "کی تعیین می‌شود", "مقدارها"],
    [[d["name"], d["criterion"], d["when"], " · ".join(v["v"] for v in d["values"])] for d in M["dims"]]) +
    "\n\n«لحن» در این اسکیل نام سه بُعد فاصله، قاطعیت و دماست. سیاق جداست، چون مقسمش نوع سند است، نه حال‌وهوای جمله‌ها. غایت، شاهد، جایگاه و ساخت چهار محور سبک‌اند (style-framework.md).")

ex = ["## ۳. هر مقدار، با نشانه و مثال"]
for d in M["dims"]:
    ex.append(f"### {d['name']}\n\n" + table(["مقدار", "نشانه", "مثال"],
              [[v["v"], v["desc"], f"«{v['ex']}»" if d["key"] != "rhythm" else v["ex"]] for v in d["values"]]))
out.append("\n\n".join(ex))

out.append("## ۴. ماتریس سیاق در برابر لحن و جایگاه و آهنگ\n\n" +
           f"{SYM['ok']} مناسب · {SYM['caution']} فقط با دلیل · {SYM['no']} نامناسب. {M['caution_rule']}\n\n" +
           table(["سیاق"] + [f"{DIM[k]['name']}: " + " / ".join(v["v"] for v in DIM[k]["values"]) for k in ["position"] + TONE],
                 [[reg] + [reg_cell(reg, k) for k in ["position"] + TONE] for reg in [v["v"] for v in DIM["register"]["values"]]]) +
           "\n\n" + table(["سیاق", "آهنگ‌های نامناسب یا با احتیاط"],
                          [[reg, "، ".join(f"{v} {SYM[l]}" for v, l in M["register_limits"].get(reg, {}).get("rhythm", {}).items()) or "همه مناسب"]
                           for reg in [v["v"] for v in DIM["register"]["values"]]]))

keys = ["purpose", "evidence", "position", "structure", "register", "distance", "certainty", "warmth", "rhythm"]
out.append("## ۵. ماتریس نسخه‌ها\n\nمقدار پررنگ پیش‌فرض نسخه است و مقدارهای داخل پرانتز هم برای آن نسخه معنا دارند. هر مقدار دیگری برای آن نسخه بی‌معناست و در صفحه‌ی تنظیمات غیرفعال است.\n\n" +
           table(["نسخه", "کاربرد"] + [DIM[k]["name"] for k in keys],
                 [[r["name"], r["use"]] + [recipe_cell(r, k) for k in keys] for r in M["recipes"]]) +
           "\n\n" + table(["نسخه", "واحد روایت", "پرسش پیونددهنده", "جای نتیجه"],
                          [[r["name"], r["unit"], r["link"], r["payoff"]] for r in M["recipes"]]))

out.append("## ۶. ماتریس نوع بخش در متن بلند\n\nپیش‌فرض لحن و آهنگ هر تیتر در روایت سطح ۱. نمونه‌ی مشتری یا صحنه‌ی واقعی معمولاً یک پاراگراف درون یک بخش است، نه بخشی جدا؛ برای همین در این جدول نیامده و قاعده‌اش در بخش ۷ است.\n\n" +
           table(["نوع بخش", "کار بخش", "فاصله", "قاطعیت", "دما", "آهنگ", "واحد روایت"],
                 [[s["name"], s["job"]] + [s["def"][k] for k in TONE + ["rhythm"]] + [s["unit"]] for s in M["sections"]]))

out.append("""## ۷. قاعده‌ی حرکت لحن میان بخش‌ها

- **ثابت در کل متن:** سیاق و جایگاه. جایگاه فقط در مرز بخش و با دلیل عوض می‌شود.
- **در هر مرز:** فاصله، قاطعیت و دما هر کدام حداکثر یک پله جابه‌جا می‌شوند. آهنگ اگر به همسایه‌اش برود آزاد است، وگرنه آغاز بخش تازه یک جمله‌ی پل می‌خواهد.
- **درون یک بخش:** فقط یک پاراگراف می‌تواند از لحن بخش جدا شود، مثلاً پاراگراف نمونه‌ی واقعی که گرم‌تر و نزدیک‌تر است.
- **سیاق بر همه مقدم است:** اگر لحن بخشی با سیاق متن در خانه‌ی ✗ بیفتد، لحن بخش عوض می‌شود، نه سیاق.

همسایه‌های آهنگ:

""" + table(["آهنگ", "همسایه‌ها"], [[k, "، ".join(v)] for k, v in M["neighbours"].items()]) + """

در سند راهبردی با بخش‌های پیش‌فرض، از «معرفی مدل» (تحلیلی میانه) به «وضع موجود» (گزارشی برند) و از «برنامه» (گزارشی برند) به «ریسک‌ها» (تحلیلی میانه) پرش آهنگ هست، پس هر دو بخش با جمله‌ی پل آغاز می‌شوند.""")

out.append("""## ۸. آنچه در بازبینی این ماتریس اصلاح شد

- **استدلال روزنامه‌ای:** سیاق پیش‌فرضش رسمی‌انسانی بود و فاصله‌اش نزدیک، در حالی که نزدیک در رسمی‌انسانی «با احتیاط» است. سیاق پیش‌فرض به نیمه‌رسمی تغییر کرد.
- **سوگ‌نامه:** قاطعیت پیش‌فرض «قاطع» بود؛ سوگ‌نامه ادعای بحث‌برانگیز ندارد و «سنجیده» درست‌تر است.
- **ریسک‌ها:** «محتاط» بود و در سند راهبردی میان «برنامه» و «چشم‌انداز» که هر دو قاطع‌اند، دو پله پرش می‌ساخت. به «سنجیده» تغییر کرد.
- **نمونه یا روایت مشتری:** از فهرست نوع بخش‌ها بیرون آمد، چون با قاعده‌ی یک‌پله‌ای ناسازگار بود. حالا یک پاراگراف مجاز درون بخش است.
- **خبر کوتاه:** آهنگ فشرده در سیاق رسمی‌انسانی «با احتیاط» علامت خورده بود، در حالی که پیش‌فرض همین نسخه است. محدودیت برداشته شد.
- **سیاق علمی:** به هیچ نسخه‌ای وصل نبود. حالا در تحلیل مفهومی، جدل، عبرت تاریخی، توضیح و آموزش، توجیه راهبردی و گزارش نهادی مجاز است.
- **«با احتیاط» در برابر پیش‌فرض نسخه:** وقتی نسخه‌ای مقداری را پیش‌فرض گرفته که در سیاقش «با احتیاط» است، مانند نزدیکی و شور در خطابه، دلیلش همان نسخه است و تناقضی نیست.""")

out.append("""## ۹. شواهد و حد اعتماد

- **آهنگ** سنجیده شده است، روی پیکره‌ی ۶۲۰ متن نُه نویسنده و یازده گزارش شرکت‌ها (style-evidence.md).
- **سیاق** از قاعده‌های تشخیص سیاق در writing-style.md آمده، نه از سنجش آماری.
- **فاصله، قاطعیت و دما**، مجازها و پیش‌فرض‌های جدول‌های ۵ و ۶ قرارداد اسکیل‌اند. از خواندن پیکره، سه مقاله‌ی دیلویت و آزمون‌های سبک با کاربر بیرون آمده‌اند و هنوز سنجیده نشده‌اند. ابزار `style_check` امروز فقط آهنگ را می‌سنجد.""")

(ROOT / "references" / "tone-matrix.md").write_text("\n\n".join(out) + "\n", encoding="utf-8")
print("wrote references/tone-matrix.md")
